const ART_KEYS = new Set(ITEM_ARTS.map((a) => a.key));
export const isArtKey = (k) => ART_KEYS.has(String(k || ""));
// "art:xp-potion" → "xp-potion", 일러스트가 아니면 ""
export const artKeyOf = (icon) => {
  const s = String(icon ?? "");
  if (!s.startsWith(ART_PREFIX)) return "";
  const k = s.slice(ART_PREFIX.length);
  return ART_KEYS.has(k) ? k : "";
};

