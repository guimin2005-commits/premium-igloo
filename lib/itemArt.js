// 한 줄에서 같은 색이 이어지는 칸을 묶고, 바로 윗줄과 모양이 같으면 세로로 늘린다 — key 마다 한 번만 만든다
const bodies = new Map();
function bodyOf(key) {
  if (bodies.has(key)) return bodies.get(key);
  const s = SPRITES[key];
  let out = "";
  if (s) {
    const open = new Map(); // "x,w,색" → 아직 닫지 않은 rect
    const done = [];
    s.map.forEach((row, y) => {
      const runs = [];
      for (let x = 0; x < row.length; ) {
        const c = row[x];
        let e = x + 1;
        while (e < row.length && row[e] === c) e++;
        if (c !== ".") runs.push([x, e - x, ART_PALETTE[s.pal[c]]]);
        x = e;
      }
      const seen = new Set();
      for (const [x, w, fill] of runs) {
        const id = `${x},${w},${fill}`;
        seen.add(id);
        const r = open.get(id);
        if (r && r.y + r.h === y) r.h++;
        else {
          if (r) done.push(r);
          open.set(id, { x, y, w, h: 1, fill });
        }
      }
      for (const [id, r] of open) {
        if (seen.has(id)) continue;
        done.push(r);
        open.delete(id);
      }
    });
    done.push(...open.values());
    done.sort((a, b) => a.y - b.y || a.x - b.x);
    out = done.map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="${r.fill}"/>`).join("");
  }
  bodies.set(key, out);
  return out;
}

// svg 안쪽(rect 들)만 — React 는 <svg viewBox="0 0 16 16"> 에 이걸 넣는다.
//    예전 호출의 둘째 인자(uid)는 그대로 받아도 되지만 쓰지 않는다(그라데이션이 없어 id 가 필요 없다)
export function itemArtBody(key) {
  if (!isArtKey(key)) return "";
  return bodyOf(key);
}

// 완성된 SVG 문자열 — 서버 · node 스크립트 · 이미지 만들기에서 쓴다. size 는 16 의 배수가 가장 또렷하다({ uid } 는 무시)
export function itemArtSvg(key, { size = 48 } = {}) {
  const body = itemArtBody(key);
  if (!body) return "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="${size}" height="${size}" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}
