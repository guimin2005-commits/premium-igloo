// 📌 레벨 공식 — 누적 XP = (3·L³ + 2200·L² + 5800·L) / 40 − 200
//    (= 0.075·L³ + 55·L² + 145·L 를 정수 연산으로 쓴 것)
//    세 항이 각자 다른 구간을 맡아 성장 속도가 계속 변한다 (일정하게 +N씩 늘지 않는다):
//      · 5800L  선형  — 1~10레벨. 첫 채팅 한 번이면 Lv2, 초반이 쭉쭉 오른다
//      · 2200L² 2차   — 중반의 뼈대
//      · 3L³    3차   — 300레벨 밑에선 존재감이 없다가 후반에 폭발하는 빙벽
//    Lv1 = 0 (시작 레벨) · Lv10 6,818 · Lv100 639,300 · Lv1000 130,144,800
//
//    [3차항을 1.5배로 올린 이유]
//    일일·주간·월간 퀘스트와 출석 보상이 들어오면서 만렙 도달이 864일 → 726일로
//    16% 짧아졌다. 3차항만 키워 초반 체감(Lv10까지 6,800 수준)은 그대로 두고
//    후반만 무겁게 만들어, 퀘스트를 포함해도 894일이 걸리도록 되돌렸다.
//    증가폭: Lv50 +2% · Lv300 +11% · Lv1000 +24%
//
//    ⚠️ bot/src/leveling.js 와 반드시 같은 값이어야 한다 (봇은 별도 배포라 import 불가)
export const getCumulativeXpByLevel = (lvl) =>
  lvl <= 0 ? 0 : Math.floor((3 * lvl ** 3 + 2200 * lvl ** 2 + 5800 * lvl) / 40) - 200;

export const getLevelByXp = (xp) => {
  if (xp <= 0) return 1; // Lv1이 시작점 — 0 XP도 Lv1
  for (let l = 1; l <= 1000; l++) {
    if (xp < getCumulativeXpByLevel(l)) return l - 1;
  }
  return 1000;
};
